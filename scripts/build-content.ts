/**
 * Build the content module.
 *
 * `content/` is the source of truth and it is a directory, not a module. This
 * script turns it into one typed module that both the browser bundle and the
 * Node-side prerender can import, so the two can never disagree about what the
 * content is.
 *
 * The output is committed. It is derived, and a reader should be able to see
 * what the site is actually serving without running anything.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const contentDir = join(root, 'content');
const stopsDir = join(contentDir, 'stops');
const outFile = join(root, 'src', 'data', 'generated.ts');

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(path, 'utf8'));
}

const profile = readJson(join(contentDir, 'profile.json'));
const route = readJson(join(contentDir, 'route.json'));

const files = readdirSync(stopsDir)
  .filter((file) => file.endsWith('.json'))
  .sort();

const stops: Record<string, unknown> = {};
for (const file of files) {
  const id = file.replace(/\.json$/, '');
  stops[id] = readJson(join(stopsDir, file));
}

const header = `/**
 * AUTO-GENERATED by scripts/build-content.ts. Do not edit by hand.
 *
 * Run \`npm run generate:content\` after changing anything in \`content/\`.
 * The build does this for you, and the validator runs first so a broken file
 * never reaches this module.
 */

import type { Profile, RouteConfig, Stop } from '../core/types';

export const PROFILE_RAW: unknown =`;

const body = `${header} ${JSON.stringify(profile, null, 2)};

export const ROUTE_RAW: unknown = ${JSON.stringify(route, null, 2)};

export const STOPS_RAW: Record<string, unknown> = ${JSON.stringify(stops, null, 2)};

/** The shape the loader will narrow these to. */
export type RawProfile = Profile;
export type RawRoute = RouteConfig;
export type RawStop = Stop;
`;

writeFileSync(outFile, body, 'utf8');

console.log(
  `content: ${files.length} stops, ${Object.keys(stops).length} written to src/data/generated.ts`,
);
